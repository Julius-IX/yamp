/// One `#[derive(TsType)]`.
pub struct TypeEntry {
  pub name: &'static str,
  pub decl: fn() -> String,
}
inventory::collect!(TypeEntry);

pub const HEADER: &str = "// WARN: AUTO-GENERATED by tauri-groups. Do not edit.\n";

fn types() -> Vec<&'static TypeEntry> {
  let mut types: Vec<_> = inventory::iter::<TypeEntry>().collect();
  types.sort_by_key(|t| t.name);
  for w in types.windows(2) {
    if w[0].name == w[1].name {
      panic!(
        "two `#[derive(TsType)]` types are both named `{}`",
        w[0].name
      );
    }
  }
  types
}

/// Names of every registered `#[derive(TsType)]` type, sorted.
pub fn type_names() -> Vec<&'static str> {
  types().into_iter().map(|t| t.name).collect()
}

/// `types.ts`: every `#[derive(TsType)]` declaration, nothing else.
pub fn render_types_ts() -> String {
  let mut s = String::from(HEADER);
  for t in types() {
    s += "\n";
    s += &(t.decl)();
    s += "\n";
  }
  s
}
